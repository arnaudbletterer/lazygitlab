"""Console table and Markdown summary for flicker results."""
from analysers import DEFECT_TYPES

SHORT = {"ROWS_SHRINK": "SHRINK", "POP_IN_OUT": "POP", "EMPTY_FLASH": "EMPTY", "SPINNER_STUCK": "SPIN",
         "SELECTION_JUMP": "SEL", "SCREEN_BLEED": "BLEED", "COUNT_MISMATCH": "COUNT",
         "STALE_AFTER_SWITCH": "STALE", "EMPTY_WHILE_LOADING": "EMPTYLOAD"}


def run_id(r):
    return f"{r['scenario']} {r['fixture']} {r['latency_ms']}ms"


def console(results):
    head = ["run", "frames"] + [SHORT[t] for t in DEFECT_TYPES]
    rows = [head] + [[run_id(r), str(r["frames"])] + [str(r["counts"][t]) for t in DEFECT_TYPES]
                     for r in results]
    widths = [max(len(x[i]) for x in rows) for i in range(len(head))]
    return "\n".join("  ".join(c.ljust(w) if i == 0 else c.rjust(w) for i, (c, w) in enumerate(zip(r, widths)))
                     for r in rows)


def totals(results):
    return {t: sum(r["counts"][t] for r in results) for t in DEFECT_TYPES}


def example(r, d):
    out = [f"- **{run_id(r)}**, frame {d['frame']}"
           + (f" (previous frame {d['prev_frame']})" if d.get("prev_frame") is not None else "")
           + f", t={d['t_ms']} ms, screen {d['screen']}",
           f"  - {d['detail']}",
           f"  - keys: {'; '.join(d['keys']) or 'none'}"]
    for name in ("prev", "cur"):
        lines = d.get("lines", {}).get(name)
        if lines:
            out.append(f"  - {name} frame:")
            out.append("    ```")
            out.extend("    " + ln.rstrip() for ln in lines)
            out.append("    ```")
    return "\n".join(out)


def markdown(results):
    tot = totals(results)
    out = ["# Flicker detector results", "",
           "Generated by `python3 tools/flicker/detect.py` against the release build and the fictional "
           "mock (`tools/demo/mock_gitlab.py`). Counts are defect events, not frames: a defect that lasts "
           "several frames is counted once when it starts.", ""]
    out += ["## Verdict", "", "| defect | total | where |", "|---|---|---|"]
    for t in DEFECT_TYPES:
        where = sorted({r["scenario"] for r in results if r["counts"][t]})
        out.append(f"| {t} | {tot[t]} | {'reproduces in ' + ', '.join(where) if tot[t] else 'did not reproduce'} |")
    out += ["", "## Scenario x latency x fixtures", "",
            "| run | frames | " + " | ".join(SHORT[t] for t in DEFECT_TYPES) + " |",
            "|---|---|" + "---|" * len(DEFECT_TYPES)]
    for r in results:
        out.append(f"| {run_id(r)} | {r['frames']} | " + " | ".join(str(r["counts"][t]) for t in DEFECT_TYPES) + " |")
    out += ["", "Columns: " + ", ".join(f"{SHORT[t]} = {t}" for t in DEFECT_TYPES) + ".", "",
            "## Examples", ""]
    for t in DEFECT_TYPES:
        out.append(f"### {t}")
        out.append("")
        hits = [(r, d) for r in results for d in r["defects"] if d["type"] == t]
        if not hits:
            out += ["Not reproduced in any run.", ""]
            continue
        for r, d in hits[:3]:
            out.append(example(r, d))
        out.append("")
    return "\n".join(out) + "\n"
